const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const ts=require('typescript');
const source=fs.readFileSync('src/statsEngine.ts','utf8');
const out={};
vm.runInNewContext(ts.transpileModule(source,{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText,{exports:out,Date,Map,Set,Number,Math,Error});
const {calculateStats}=out;
const day='2026-11-25';
const sets=[{set:1,reps:12,loadKg:20,rir:2,validated:true},{set:2,reps:12,loadKg:20,rir:2,validated:true}];
const make=(results)=>({id:'review-edge',status:'partial',startedAt:day+'T10:00:00',endedAt:day+'T10:05:00',updatedAt:day+'T10:05:00',activeMs:120000,restMs:60000,pauseMs:0,targets:[{exerciseId:'std:developpe',sets:2,reps:10,loadKg:20},{exerciseId:'custom:gainage',sets:2,durationSeconds:30}],exerciseKinds:{0:'musculation',1:'musculation'},exerciseResults:results});
const period={start:day,end:day};
const stats=results=>calculateStats([make(results)],[],period,new Date(day+'T20:00:00'));
const initial=stats([{index:0,sets},{index:1,sets:[{set:1,reps:0,loadKg:0,durationSeconds:30,validated:true},{set:2,reps:0,loadKg:0,durationSeconds:30,validated:true}]}]);
assert.equal(initial.strengthSets,4);assert.equal(initial.nominalVolumeKgReps,480);assert.equal(initial.isometricSeconds,60);
const corrected=stats([{index:0,sets:[sets[0],{...sets[1],validated:false}]},{index:1,sets:[{set:1,reps:0,loadKg:0,durationSeconds:40,validated:true},{set:2,reps:0,loadKg:0,durationSeconds:30,validated:false}]}]);
assert.equal(corrected.strengthSets,2,'Invalidated series must not count');
assert.equal(corrected.nominalVolumeKgReps,240,'Only validated resistance series contribute volume');
assert.equal(corrected.isometricSeconds,40,'Edited timed series count, rest and unchecked series do not');
assert.equal(corrected.restMs,60000,'Rest must remain separate from timed work');
const allUnchecked=stats([{index:0,sets:sets.map(s=>({...s,validated:false}))},{index:1,sets:[{set:1,durationSeconds:40,validated:false}]}]);
assert.equal(allUnchecked.strengthSets,0);assert.equal(allUnchecked.isometricSeconds,0);assert.equal(allUnchecked.nominalVolumeKgReps,0);
const session=fs.readFileSync('src/SessionExecution.tsx','utf8');
assert.match(session,/completedIndexes:correctedIndexes/,'Corrected completion must be saved');
assert.match(session,/status=abandon\?'abandoned':correctedIndexes\.length===session\.targets\.length&&base\.targets\.every/,'Partial status after unchecking exercises');
console.log('PASS V31 review edge cases: isometric edits, unchecked series, volume, rest, partial session');
